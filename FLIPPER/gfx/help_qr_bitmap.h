static inline bool lab_c5_help_qr_get_module(int x, int y) {
    if((unsigned)x >= LAB_C5_HELP_QR_SIZE || (unsigned)y >= LAB_C5_HELP_QR_SIZE) return false;
    unsigned index = (unsigned)y * LAB_C5_HELP_QR_SIZE + (unsigned)x;
    return (lab_c5_help_qr_bitmap[index >> 3] & (1u << (index & 7))) != 0;
}

